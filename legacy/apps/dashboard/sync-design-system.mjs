// Bundle the official component CSS locally for both the raw dashboard and Vite.
import { readFile, writeFile } from 'node:fs/promises';
const file = new URL('./styles.css', import.meta.url);
const marker = '/* Basecoat generated components: end */';
const current = await readFile(file, 'utf8');
const authored = current.includes(marker) ? current.slice(current.indexOf(marker) + marker.length).replace(/^\n/, '') : current;
const packageRoot = new URL('./', import.meta.resolve('basecoat-css'));
let components = await readFile(new URL('basecoat.cdn.min.css', packageRoot), 'utf8');
// @property declarations must stay at the document level; all style rules are scoped.
const properties = [...components.matchAll(/@property\s+[^{}]+\{[^{}]+\}/g)].map(match => match[0]).join('\n');
components = components.replace(/@property\s+[^{}]+\{[^{}]+\}/g, '').replaceAll(':root', ':scope').replaceAll(':host', ':scope');
const license = (await readFile(new URL('../LICENSE.md', packageRoot), 'utf8')).replaceAll('*/', '* /');
const generated = `/* Basecoat 1.0.2 (Vega): official component CSS. Generated by sync-design-system.mjs.\n${license}\n*/\n${properties}\n@scope (.update-mode) {\n${components}\n}\n${marker}\n`;
const result = generated + authored;
if (process.argv.includes('--check')) {
  if (result !== current) throw new Error('Basecoat bundle is stale: run node apps/dashboard/sync-design-system.mjs');
} else await writeFile(file, result);
console.log('Basecoat 1.0.2 official Button, Field, Badge and Accordion CSS bundled locally');
